#!/usr/bin/env python3
"""A Now/Next/Later roadmap kept as one Markdown file per item, checked in CI.

Open items live in roadmap/items/<id>.md and closed ones in
roadmap/archive/<id>.md. Each file opens with TOML frontmatter fenced by `+++`.
The frontmatter is read by the stdlib's tomllib, so this script has no
dependencies and can be copied into any repo. It carries the fields a reader
would otherwise have to infer from the prose. The prose body is where the
argument lives, and no schema tries to parse it.

roadmap/README.md carries a generated index of the open items, and
roadmap/done.md carries a generated index of the archive. `check` fails when:
- either index has drifted from the item files,
- an item breaks its bucket's entry criterion,
- a ref or a relative link points at nothing, or
- (given --base) an archived entry lost a line.

Run `python roadmap.py --help` for the commands. This file is vendored from
the roadmap skill, and `--version` says which release it came from.

Copyright (c) 2026 Tommy Derngren. MIT License."""

from __future__ import annotations

import argparse
import datetime
import difflib
import glob
import json
import os
import re
import shutil
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import unquote

__version__ = "1.0.0"

BUCKETS = ("now", "next", "later")
BUCKET_TITLES = {"now": "Now", "next": "Next", "later": "Later"}
OUTCOMES = ("shipped", "declined")

OPEN_REQUIRED = frozenset({"id", "title", "bucket", "rank", "filed"})
OPEN_OPTIONAL = frozenset({"updated", "gate", "blocked_on", "refs"})
CLOSED_REQUIRED = frozenset({"id", "title", "filed", "closed", "outcome"})
CLOSED_OPTIONAL = frozenset({"updated", "gate", "refs", "shipped_as"})
QUEUE_FIELDS = frozenset({"bucket", "rank", "blocked_on"})
DATE_FIELDS = ("filed", "updated", "closed")
STRING_FIELDS = ("title", "gate", "blocked_on", "shipped_as")

INDEX_BEGIN = "<!-- BEGIN INDEX: generated by roadmap.py; edit items/*.md instead -->"
INDEX_END = "<!-- END INDEX -->"
DONE_BEGIN = "<!-- BEGIN DONE: generated by roadmap.py; edit archive/*.md instead -->"
DONE_END = "<!-- END DONE -->"

# What `new` writes as the body. It is an HTML comment, and comments don't
# count as prose, so an item nobody has argued for yet fails the body rule.
PLACEHOLDER = "<!-- What is wrong, why it matters, and what done looks like. -->"

# Every rule `check` enforces, keyed by the tag printed after each problem.
# README.md's error table has one row per key, and a test keeps them in step.
RULES = {
    "config": "roadmap.toml parses and declares each ref kind as a path template containing {}",
    "frontmatter": "the file opens with +++-fenced frontmatter that parses as TOML",
    "schema": "required fields present, none unknown, id is a kebab-case slug matching the filename",
    "bucket": "bucket is now, next or later; later <=> blocked_on",
    "rank": "rank is a positive integer, unique within its bucket",
    "dates": "dates are bare TOML dates, and none predates `filed`",
    "body": "the prose body says something (HTML comments don't count)",
    "refs": "every ref on an open item resolves in the tree",
    "ids": "an id is used once, across open and archived items",
    "links": "every relative link in open items, README.md and done.md resolves",
    "generated": "README.md's index and done.md match the item files",
    "append-only": "with --base: no archived entry is removed, moved or loses a line",
}

SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
_FRONTMATTER = re.compile(r"\A\+\+\+\n(.*?)\n\+\+\+\n?(.*)\Z", re.DOTALL)
_TOP_LEVEL_KEY = re.compile(r"\s*([A-Za-z0-9_-]+)\s*=")
_INLINE_LINK = re.compile(r"\]\(\s*(<[^>\n]*>|[^)\s]+)")
_REFERENCE_LINK = re.compile(r"^ {0,3}\[[^\]\n]+\]:[ \t]*(<[^>\n]*>|\S+)", re.MULTILINE)
_SCHEME = re.compile(r"[A-Za-z][A-Za-z0-9+.-]*:")
_COMMENT = re.compile(r"<!--.*?-->", re.DOTALL)


class UsageError(Exception):
    """A command that cannot run as asked. It is reported as `error: ...` with exit status 2, as argparse does."""


class ConfigError(UsageError):
    pass


class FrontmatterError(ValueError):
    def __init__(self, path: Path, reason: str) -> None:
        super().__init__(f"{path}: {reason}")
        self.path, self.reason = path, reason


@dataclass(frozen=True)
class Problem:
    path: Path
    rule: str
    message: str
    line: int | None = None

    def __str__(self) -> str:
        where = f"{self.path}:{self.line}" if self.line else f"{self.path}"
        return f"{where}: {self.message} [{self.rule}]"


@dataclass(frozen=True)
class Roadmap:
    """Where a roadmap lives and how its refs resolve. `root` is what refs are
    relative to, which is the roadmap directory's parent unless roadmap.toml says
    otherwise."""

    dir: Path
    root: Path
    ref_kinds: dict[str, tuple[str, ...]]

    @property
    def items_dir(self) -> Path:
        return self.dir / "items"

    @property
    def archive_dir(self) -> Path:
        return self.dir / "archive"

    @property
    def readme(self) -> Path:
        return self.dir / "README.md"

    @property
    def done(self) -> Path:
        return self.dir / "done.md"


@dataclass(frozen=True)
class Item:
    path: Path
    meta: dict
    body: str
    archived: bool = False

    @property
    def id(self) -> str:
        return str(self.meta.get("id", self.path.stem))

    @property
    def title(self) -> str:
        return str(self.meta.get("title", self.id))

    @property
    def bucket(self) -> str:
        return str(self.meta.get("bucket", ""))

    @property
    def rank(self) -> int:
        rank = self.meta.get("rank")
        return rank if isinstance(rank, int) and not isinstance(rank, bool) else 0


# --- loading ----------------------------------------------------------------


def open_roadmap(directory: Path | str) -> Roadmap:
    """Read roadmap.toml if there is one. `files` is always a ref kind, meaning
    a path relative to the root. Any other kind must be declared."""
    directory = Path(directory)
    config_path = directory / "roadmap.toml"
    config: dict = {}
    if config_path.exists():
        try:
            config = tomllib.loads(config_path.read_text())
        except tomllib.TOMLDecodeError as exc:
            raise ConfigError(f"{config_path}: malformed TOML: {exc} [config]") from exc
    if unknown := set(config) - {"root", "refs"}:
        raise ConfigError(f"{config_path}: unknown key(s) {', '.join(sorted(unknown))} [config]")
    root = config.get("root", "..")
    if not isinstance(root, str):
        raise ConfigError(f"{config_path}: root must be a path string [config]")
    refs = config.get("refs", {})
    if not isinstance(refs, dict):
        raise ConfigError(f"{config_path}: refs must be a table of path templates [config]")

    kinds: dict[str, tuple[str, ...]] = {"files": ("{}",)}
    for kind, templates in refs.items():
        templates = [templates] if isinstance(templates, str) else templates
        if not (isinstance(templates, list) and templates and all(isinstance(t, str) and "{}" in t for t in templates)):
            raise ConfigError(
                f"{config_path}: refs.{kind} must be a path template containing {{}}, or a list of them [config]"
            )
        kinds[kind] = tuple(templates)
    return Roadmap(dir=directory, root=Path(os.path.normpath(directory / root)), ref_kinds=kinds)


def parse(path: Path, archived: bool = False) -> Item:
    """Split one item file into its metadata and its prose. Raises
    FrontmatterError, with the path in the message, on anything tomllib or the
    fence rejects."""
    match = _FRONTMATTER.match(path.read_text())
    if match is None:
        raise FrontmatterError(path, "no +++-fenced TOML frontmatter at the top of the file")
    try:
        meta = tomllib.loads(match.group(1))
    except tomllib.TOMLDecodeError as exc:
        raise FrontmatterError(path, f"malformed TOML frontmatter: {exc}") from exc
    return Item(path=path, meta=meta, body=match.group(2), archived=archived)


def load(rm: Roadmap) -> tuple[list[Item], list[Item], list[Problem]]:
    """Every open item, in index order (by bucket, then rank). Every archived
    item, in done.md order (newest first). And every file that would not parse,
    as problems, so one broken file doesn't hide the rest."""
    items, problems = _load_dir(rm.items_dir, archived=False)
    archived, more = _load_dir(rm.archive_dir, archived=True)
    items.sort(key=lambda i: (BUCKETS.index(i.bucket) if i.bucket in BUCKETS else len(BUCKETS), i.rank, i.id))
    archived.sort(key=lambda i: i.id)
    archived.sort(key=lambda i: str(i.meta.get("closed", "")), reverse=True)
    return items, archived, problems + more


def _load_dir(directory: Path, archived: bool) -> tuple[list[Item], list[Problem]]:
    items, problems = [], []
    for path in sorted(directory.glob("*.md")):
        try:
            items.append(parse(path, archived))
        except FrontmatterError as exc:
            problems.append(Problem(path, "frontmatter", exc.reason))
    return items, problems


# --- validation -------------------------------------------------------------


def validate(rm: Roadmap, items: list[Item], archived: list[Item]) -> list[Problem]:
    """Every rule except `generated` and `append-only`, as a list of problems.
    An empty list is a clean roadmap. Problems are collected rather than
    raised, so one run reports all of them instead of just the first."""
    problems: list[Problem] = []
    for item in items + archived:
        problems += _schema_problems(item)
        problems += _date_problems(item)
        problems += _body_problems(item)
        problems += _ref_problems(item, rm)
    for item in items:
        problems += _bucket_problems(item)
        problems += _rank_problems(item)
    return problems + _collision_problems(items) + _id_problems(items + archived) + link_problems(rm, items)


def check(rm: Roadmap, base: str | None = None) -> list[Problem]:
    """Everything `check` enforces: parse failures, `validate()`, drift in
    the generated files, and (given a git base) append-only."""
    items, archived, problems = load(rm)
    problems += validate(rm, items, archived)
    problems += generated_problems(rm, items, archived)
    if base is not None:
        problems += append_only_problems(rm, base)
    return problems


def _schema_problems(item: Item) -> list[Problem]:
    """The fields themselves. Open and archived items have different schemas.
    The id has to agree with the filename, so that a file can be found from its
    index entry."""
    required, optional = (CLOSED_REQUIRED, CLOSED_OPTIONAL) if item.archived else (OPEN_REQUIRED, OPEN_OPTIONAL)
    problems = []
    fields = set(item.meta)
    if missing := required - fields:
        problems.append(f"missing required field(s) {', '.join(sorted(missing))}")
    unknown = fields - required - optional
    if item.archived and (queue := unknown & QUEUE_FIELDS):
        problems.append(
            f"queue field(s) {', '.join(sorted(queue))} belong to open items; an archived item has left the queue"
        )
        unknown -= queue
    if unknown:
        problems.append(f"unknown field(s) {', '.join(sorted(unknown))}")
    if "id" in item.meta and item.meta["id"] != item.path.stem:
        problems.append(f"id {item.meta['id']!r} does not match its filename")
    if not SLUG.fullmatch(item.path.stem):
        problems.append(
            f"filename {item.path.stem!r} is not a kebab-case slug (lowercase letters, digits, single hyphens)"
        )
    problems.extend(
        f"{name} must be a non-empty string"
        for name in STRING_FIELDS
        if name in item.meta and not (isinstance(item.meta[name], str) and item.meta[name].strip())
    )
    if item.archived and "outcome" in item.meta and item.meta["outcome"] not in OUTCOMES:
        problems.append(f"outcome {item.meta['outcome']!r} is not one of {', '.join(OUTCOMES)}")
    return [Problem(item.path, "schema", message) for message in problems]


def _bucket_problems(item: Item) -> list[Problem]:
    """The one entry criterion a field can carry. Later is for the undecided,
    so a later item names the decision it is waiting on, and naming one
    anywhere else contradicts the bucket. Now and Next differ only in
    priority. Now is the top of the list, like a planned sprint. Neither one
    tracks who is working on what: an item leaves the roadmap when it is
    closed in the same merge as its code."""
    if "bucket" not in item.meta:
        return []
    if item.bucket not in BUCKETS:
        return [Problem(item.path, "bucket", f"bucket {item.meta['bucket']!r} is not one of {', '.join(BUCKETS)}")]

    problems = []
    blocked = item.meta.get("blocked_on")
    if item.bucket == "later" and not blocked:
        problems.append("a 'later' item must name what it is blocked_on")
    if item.bucket != "later" and blocked:
        problems.append(f"blocked_on belongs to a 'later' item; this one is {item.bucket!r}")
    return [Problem(item.path, "bucket", message) for message in problems]


def _rank_problems(item: Item) -> list[Problem]:
    rank = item.meta.get("rank")
    if rank is None or (isinstance(rank, int) and not isinstance(rank, bool) and rank > 0):
        return []
    return [Problem(item.path, "rank", f"rank must be a positive integer, not {rank!r}")]


def _date_problems(item: Item) -> list[Problem]:
    """A bare TOML date parses to datetime.date. A quoted one parses to str, and
    then sorts and renders wrong. The difference is invisible in the file, which
    is why it gets a check."""
    problems = [
        Problem(item.path, "dates", f"{name} must be a bare TOML date (2026-09-06), not {item.meta[name]!r}")
        for name in DATE_FIELDS
        if name in item.meta and type(item.meta[name]) is not datetime.date
    ]
    filed = item.meta.get("filed")
    if type(filed) is datetime.date:
        problems.extend(
            Problem(item.path, "dates", f"{name} {item.meta[name]} is before filed {filed}")
            for name in DATE_FIELDS[1:]
            if type(item.meta.get(name)) is datetime.date and item.meta[name] < filed
        )
    return problems


def _body_problems(item: Item) -> list[Problem]:
    if _COMMENT.sub("", item.body).strip():
        return []
    return [Problem(item.path, "body", "has no prose; an item with only a title is not an item")]


def _ref_problems(item: Item, rm: Roadmap) -> list[Problem]:
    """Every ref that points at something that is not there. Prose could never
    do this check. Only open items are resolved: an archived entry describes the
    tree as it was, and it is allowed to point at things that have since been
    renamed."""
    refs = item.meta.get("refs", {})
    if not isinstance(refs, dict):
        return [Problem(item.path, "refs", "refs must be a table of lists, e.g. [refs] files = [...]")]

    problems = []
    for kind, entries in refs.items():
        if not (isinstance(entries, list) and all(isinstance(e, str) for e in entries)):
            problems.append(f"refs.{kind} must be a list of strings")
            continue
        if item.archived:
            continue
        if (templates := rm.ref_kinds.get(kind)) is None:
            problems.append(f"unknown ref kind {kind!r}; roadmap.toml declares {', '.join(sorted(rm.ref_kinds))}")
            continue
        for entry in entries:
            if not _resolves(rm.root, templates, entry):
                where = "does not exist" if templates == ("{}",) else f"matches none of {', '.join(templates)}"
                problems.append(f"refs.{kind} {entry!r} {where}")
    return [Problem(item.path, "refs", message) for message in problems]


def _resolves(root: Path, templates: tuple[str, ...], entry: str) -> bool:
    return any(glob.glob(str(root / t.replace("{}", glob.escape(entry)))) for t in templates)


def _collision_problems(items: list[Item]) -> list[Problem]:
    """Two open items claiming the same position in a bucket."""
    problems = []
    ranks: dict[tuple[str, int], Path] = {}
    for item in items:
        if item.bucket not in BUCKETS or item.rank <= 0:
            continue
        if (other := ranks.setdefault((item.bucket, item.rank), item.path)) != item.path:
            problems.append(
                Problem(item.path, "rank", f"rank {item.rank} is already taken in {item.bucket!r} by {other}")
            )
    return problems


def _id_problems(everything: list[Item]) -> list[Problem]:
    """An id is an address. A closed id cannot be reused, and an item cannot
    be both open and closed."""
    problems = []
    seen: dict[str, Item] = {}
    for item in everything:
        first = seen.setdefault(item.id, item)
        if first is item:
            continue
        if first.archived != item.archived:
            message = f"id {item.id!r} is both open and archived (also {first.path})"
        else:
            message = f"duplicate id {item.id!r}, also in {first.path}"
        problems.append(Problem(item.path, "ids", message))
    return problems


# --- links ------------------------------------------------------------------


def _mask_code(text: str) -> str:
    """Blank out fenced blocks and inline code spans, keeping every offset, so a
    link inside a code example is neither checked nor rewritten."""
    out, fence = [], None
    for line in text.splitlines(keepends=True):
        marker = re.match(r"\s{0,3}(`{3,}|~{3,})", line)
        if fence is None and marker:
            fence = marker.group(1)
        elif fence is not None:
            if marker and marker.group(1)[0] == fence[0] and len(marker.group(1)) >= len(fence):
                fence = None
        else:
            out.append(re.sub(r"(`+).+?\1", lambda m: " " * len(m.group()), line))
            continue
        out.append(re.sub(r"[^\n]", " ", line))
    return "".join(out)


def _links(text: str) -> list[tuple[int, int, str]]:
    """(start, end, target) for every inline and reference-style link
    destination outside code, with any <angle brackets> stripped from the
    target."""
    masked = _mask_code(text)
    found = []
    for pattern in (_INLINE_LINK, _REFERENCE_LINK):
        for match in pattern.finditer(masked):
            start, end = match.span(1)
            target = text[start:end]
            if target.startswith("<"):
                start, end, target = start + 1, end - 1, target[1:-1]
            found.append((start, end, target))
    return sorted(found)


def _local_part(target: str) -> tuple[str, str] | None:
    """Split a relative link into its path and its #fragment or ?query. Returns
    None for anything that is not a relative path: URLs, mailto:, bare anchors
    and repo-absolute /paths."""
    if not target or _SCHEME.match(target) or target.startswith(("#", "/")):
        return None
    cut = min((i for i in (target.find("#"), target.find("?")) if i != -1), default=len(target))
    return (target[:cut], target[cut:]) if target[:cut] else None


def link_problems(rm: Roadmap, items: list[Item]) -> list[Problem]:
    """Every relative link in the open items, README.md and done.md that
    points at nothing. Archived entries are exempt, for the same reason their
    refs are. So are the generated blocks: `index` rewrites them from the
    files, and a stale index is reported as `generated`. Checking their links
    too would stop `index` from repairing an index that links to a deleted
    item."""
    problems = []
    generated = {rm.readme: (INDEX_BEGIN, INDEX_END), rm.done: (DONE_BEGIN, DONE_END)}
    for path in [i.path for i in items] + [p for p in (rm.readme, rm.done) if p.exists()]:
        text = path.read_text()
        skip = _block_span(text, *generated[path]) if path in generated else None
        for start, _, target in _links(text):
            if skip and skip[0] <= start < skip[1]:
                continue
            local = _local_part(target)
            if local and not (path.parent / unquote(local[0])).exists():
                line = text.count("\n", 0, start) + 1
                problems.append(Problem(path, "links", f"links to {target!r}, which does not exist", line))
    return problems


def retarget_links(text: str, before: Path, after: Path, moves: dict[Path, Path]) -> str:
    """Rewrite the relative links in a file's text. `before` is the directory
    the file lived in, `after` is the one it will live in, and `moves` maps old
    paths to new ones. Each link is kept pointing at the same file, including a
    file that moved."""
    moves = {Path(os.path.normpath(k)): Path(os.path.normpath(v)) for k, v in moves.items()}
    pieces, last = [], 0
    for start, end, target in _links(text):
        local = _local_part(target)
        if local is None:
            continue
        resolved = Path(os.path.normpath(before / unquote(local[0])))
        resolved = moves.get(resolved, resolved)
        if Path(os.path.normpath(after / unquote(local[0]))) == resolved:
            continue
        pieces += [text[last:start], Path(os.path.relpath(resolved, after)).as_posix() + local[1]]
        last = end
    return "".join(pieces) + text[last:]


# --- generated files --------------------------------------------------------


def render_index(items: list[Item]) -> str:
    """The README's index block, between its markers. There is one line per item, and
    every one is read back out of the item files."""
    lines = [INDEX_BEGIN, ""]
    for bucket in BUCKETS:
        in_bucket = [i for i in items if i.bucket == bucket]
        lines += [f"### {BUCKET_TITLES[bucket]} ({len(in_bucket)})", ""]
        if not in_bucket:
            lines += ["*Empty.*", ""]
            continue
        for item in in_bucket:
            lines.append(
                f"{item.rank}. [{item.title}](items/{item.path.name}) — filed {item.meta.get('filed')}{_note(item)}"
            )
        lines.append("")
    lines.append(INDEX_END)
    return "\n".join(lines)


def _note(item: Item) -> str:
    if blocked := item.meta.get("blocked_on"):
        return f"<br>  **Blocked on:** {blocked}"
    if gate := item.meta.get("gate"):
        return f"<br>  **Gate:** {gate}"
    return ""


def render_done(archived: list[Item]) -> str:
    """done.md's block: one line per closed item, newest first, grouped by the
    month it closed. Each line is short enough to grep, and it links to the full
    entry."""
    lines = [DONE_BEGIN, ""]
    if not archived:
        lines += ["*Empty.*", ""]
    groups: dict[str, list[Item]] = {}
    for item in archived:
        groups.setdefault(str(item.meta.get("closed", "undated"))[:7], []).append(item)
    for month, group in groups.items():
        lines += [f"### {month} ({len(group)})", ""]
        for item in group:
            shipped_as = f" as `{item.meta['shipped_as']}`" if item.meta.get("shipped_as") else ""
            lines.append(
                f"- **{item.meta.get('outcome')}** [{item.title}](archive/{item.path.name})"
                f" — closed {item.meta.get('closed')}{shipped_as}"
            )
        lines.append("")
    lines.append(DONE_END)
    return "\n".join(lines)


def _block_span(text: str, begin: str, end: str) -> tuple[int, int] | None:
    """Where the generated block sits in `text`, markers included, or None if
    the markers are missing. The begin marker is matched by its prefix
    (`<!-- BEGIN INDEX`), so older wording still counts."""
    opening = re.search(re.escape(begin.split(":")[0]) + r".*?-->", text)
    stop = text.find(end, opening.end()) if opening else -1
    return (opening.start(), stop + len(end)) if opening and stop != -1 else None


def splice(text: str, begin: str, end: str, block: str, path: Path) -> str:
    """`text` with the block between the markers replaced, markers included. It
    refuses a file that is missing the markers rather than guessing where the
    block goes. A marker in older wording is rewritten, not rejected."""
    if (span := _block_span(text, begin, end)) is None:
        raise UsageError(f"{path}: generated-block markers not found; expected {begin} ... {end}")
    return text[: span[0]] + block + text[span[1] :]


def _generated_targets(rm: Roadmap, items: list[Item], archived: list[Item]) -> list[tuple[Path, str, str, str]]:
    return [
        (rm.readme, INDEX_BEGIN, INDEX_END, render_index(items)),
        (rm.done, DONE_BEGIN, DONE_END, render_done(archived)),
    ]


def generated_problems(rm: Roadmap, items: list[Item], archived: list[Item]) -> list[Problem]:
    problems = []
    for path, begin, end, block in _generated_targets(rm, items, archived):
        if not path.exists():
            problems.append(Problem(path, "generated", "is missing; `roadmap.py init` writes one"))
            continue
        text = path.read_text()
        try:
            stale = text != splice(text, begin, end, block, path)
        except UsageError:
            problems.append(Problem(path, "generated", f"markers not found; expected {begin} ... {end}"))
            continue
        if stale:
            problems.append(Problem(path, "generated", "generated block is stale; run `roadmap.py index`"))
    return problems


def write_generated(rm: Roadmap) -> list[Path]:
    """Regenerate README.md's index and done.md. Returns the files that changed."""
    items, archived, _ = load(rm)
    written = []
    for path, begin, end, block in _generated_targets(rm, items, archived):
        text = path.read_text()
        if (new := splice(text, begin, end, block, path)) != text:
            path.write_text(new)
            written.append(path)
    return written


# --- append-only ------------------------------------------------------------


def _git(cwd: Path, *args: str) -> str:
    try:
        return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=True).stdout
    except FileNotFoundError as exc:
        raise UsageError("--base needs git on PATH") from exc
    except subprocess.CalledProcessError as exc:
        raise UsageError(f"git {' '.join(args)} failed: {exc.stderr.strip()}") from exc


def append_only_problems(rm: Roadmap, base: str) -> list[Problem]:
    """Every archived entry that existed at `base` must still exist, and it may
    only have gained lines. That leaves room for a dated annotation added under
    a claim that later events falsified, and for nothing else."""
    top = Path(_git(rm.dir, "rev-parse", "--show-toplevel").strip())
    prefix = Path(os.path.relpath(rm.archive_dir.resolve(), top)).as_posix()
    problems = []
    for rel in _git(top, "ls-tree", "-r", "--name-only", base, "--", prefix).splitlines():
        if not rel.endswith(".md"):
            continue
        shown = rm.archive_dir / Path(rel).relative_to(prefix)
        if not (top / rel).exists():
            problems.append(
                Problem(
                    shown, "append-only", f"existed at {base} and is gone; archived entries are never deleted or moved"
                )
            )
            continue
        old = _git(top, "show", f"{base}:{rel}").splitlines()
        new = (top / rel).read_text().splitlines()
        for tag, i1, i2, _, _ in difflib.SequenceMatcher(None, old, new, autojunk=False).get_opcodes():
            if tag in ("replace", "delete"):
                lines = f"line {i1 + 1}" if i2 - i1 == 1 else f"lines {i1 + 1}-{i2}"
                problems.append(
                    Problem(
                        shown,
                        "append-only",
                        f"changes {lines} as of {base}; archived entries only take added lines (dated annotations)",
                        i1 + 1,
                    )
                )
                break
    return problems


# --- editing frontmatter ----------------------------------------------------


def _toml(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, datetime.date)):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    raise TypeError(f"no TOML rendering for {value!r}")


def edit_frontmatter(path: Path, *, remove: frozenset[str] = frozenset(), assign: dict | None = None) -> str:
    """The file's text with top-level frontmatter keys removed or set. All other
    lines are left alone, including comments and tables. The edit is parsed back
    and checked, so a layout it cannot handle safely (such as a multi-line
    value) is refused rather than mangled."""
    assign = assign or {}
    text = path.read_text()
    match = _FRONTMATTER.match(text)
    if match is None:
        raise UsageError(f"{path}: no +++-fenced TOML frontmatter at the top of the file")
    lines = match.group(1).split("\n")
    cut = next((i for i, line in enumerate(lines) if line.lstrip().startswith("[")), len(lines))
    top, tables = lines[:cut], lines[cut:]

    kept, pending = [], dict(assign)
    for line in top:
        key = m.group(1) if (m := _TOP_LEVEL_KEY.match(line)) else None
        if key in remove:
            continue
        kept.append(f"{key} = {_toml(pending.pop(key))}" if key in pending else line)
    while kept and not kept[-1].strip():
        kept.pop()
    kept += [f"{key} = {_toml(value)}" for key, value in pending.items()]
    if tables:
        kept.append("")

    head = "\n".join(kept + tables)
    try:
        meta = tomllib.loads(head)
    except tomllib.TOMLDecodeError as exc:
        raise UsageError(f"{path}: could not edit the frontmatter safely ({exc}); edit it by hand") from exc
    if any(k in meta for k in remove) or any(meta.get(k) != v for k, v in assign.items()):
        raise UsageError(f"{path}: could not edit the frontmatter safely; edit it by hand")
    return f"+++\n{head}\n+++\n{match.group(2)}"


# --- commands ---------------------------------------------------------------


def _today(args: argparse.Namespace) -> datetime.date:
    return args.date or datetime.date.today()


def _open_item(rm: Roadmap, item_id: str) -> Item:
    path = rm.items_dir / f"{item_id}.md"
    if not path.exists():
        where = " it is already closed" if (rm.archive_dir / f"{item_id}.md").exists() else ""
        raise UsageError(f"no open item {item_id!r} in {rm.items_dir}{';' + where if where else ''}")
    try:
        return parse(path)
    except FrontmatterError as exc:
        raise UsageError(str(exc)) from exc


def _next_rank(rm: Roadmap, bucket: str) -> int:
    items, _, _ = load(rm)
    return 1 + max((i.rank for i in items if i.bucket == bucket), default=0)


def _report(problems: list[Problem]) -> int:
    if problems:
        print(f"{len(problems)} roadmap problem(s):", file=sys.stderr)
        print("\n".join(str(p) for p in problems), file=sys.stderr)
        return 1
    return 0


def cmd_check(rm: Roadmap, args: argparse.Namespace) -> int:
    if code := _report(check(rm, args.base)):
        return code
    items, archived, _ = load(rm)
    print(f"Roadmap OK: {len(items)} open, {len(archived)} archived.")
    return 0


def cmd_index(rm: Roadmap, args: argparse.Namespace) -> int:
    items, archived, problems = load(rm)
    if code := _report(problems + validate(rm, items, archived)):
        return code
    written = write_generated(rm)
    print(f"Wrote {', '.join(map(str, written))}." if written else "Index already up to date.")
    return 0


def cmd_new(rm: Roadmap, args: argparse.Namespace) -> int:
    if not SLUG.fullmatch(args.id):
        raise UsageError(f"id {args.id!r} is not a kebab-case slug (lowercase letters, digits, single hyphens)")
    for existing in (rm.items_dir / f"{args.id}.md", rm.archive_dir / f"{args.id}.md"):
        if existing.exists():
            raise UsageError(f"{existing} already exists; ids are never reused")
    if (args.bucket == "later") != bool(args.blocked_on):
        raise UsageError("--blocked-on is required for a 'later' item and forbidden for any other")

    today = _today(args)
    meta: dict = {"id": args.id, "title": args.title, "bucket": args.bucket, "rank": _next_rank(rm, args.bucket)}
    meta["filed"] = today
    if args.gate:
        meta["gate"] = args.gate
    if args.blocked_on:
        meta["blocked_on"] = args.blocked_on
    refs: dict[str, list[str]] = {}
    for ref in args.ref:
        kind, sep, value = ref.partition(":")
        if not sep or not kind or not value:
            raise UsageError(f"--ref {ref!r} must look like KIND:VALUE, e.g. files:src/app.py")
        refs.setdefault(kind, []).append(value)

    lines = ["+++", *(f"{k} = {_toml(v)}" for k, v in meta.items())]
    if refs:
        lines += ["", "[refs]", *(f"{k} = [{', '.join(_toml(v) for v in vs)}]" for k, vs in refs.items())]
    lines += ["+++", "", args.body or PLACEHOLDER, ""]

    rm.items_dir.mkdir(parents=True, exist_ok=True)
    path = rm.items_dir / f"{args.id}.md"
    path.write_text("\n".join(lines))
    write_generated(rm)
    print(f"Created {path} in {args.bucket!r} at rank {meta['rank']}.")
    if not args.body:
        print("Its body is a placeholder; `check` fails until the prose is written.")
    return 0


def cmd_move(rm: Roadmap, args: argparse.Namespace) -> int:
    item = _open_item(rm, args.id)
    if item.bucket == args.bucket:
        raise UsageError(f"{item.path} is already in {args.bucket!r}")
    if (args.bucket == "later") != bool(args.blocked_on):
        raise UsageError("--blocked-on is required when moving to 'later' and forbidden otherwise")
    assign: dict = {"bucket": args.bucket, "rank": _next_rank(rm, args.bucket)}
    if args.blocked_on:
        assign["blocked_on"] = args.blocked_on
    remove = frozenset({"blocked_on"}) if item.bucket == "later" else frozenset()
    item.path.write_text(edit_frontmatter(item.path, remove=remove, assign=assign))
    write_generated(rm)
    print(f"Moved {item.path} to {args.bucket!r} at rank {assign['rank']}.")
    if remove:
        print("It was blocked on a decision; record in its prose what was decided.")
    return 0


def cmd_close(rm: Roadmap, args: argparse.Namespace) -> int:
    item = _open_item(rm, args.id)
    assign: dict = {"closed": _today(args), "outcome": args.outcome}
    if args.shipped_as:
        assign["shipped_as"] = args.shipped_as
    target = rm.archive_dir / item.path.name
    if target.exists():
        raise UsageError(f"{target} already exists; ids are never reused")

    moves = {item.path: target}
    text = edit_frontmatter(item.path, remove=QUEUE_FIELDS, assign=assign)
    text = retarget_links(text, item.path.parent, target.parent, moves)

    # Links into the moved file from open items and the README follow it.
    # Archived entries are never edited, and they are exempt from the link check.
    others = [p for p in sorted(rm.items_dir.glob("*.md")) if p != item.path] + [rm.readme]
    rewritten = {p: retarget_links(p.read_text(), p.parent, p.parent, moves) for p in others if p.exists()}

    rm.archive_dir.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    item.path.unlink()
    original = {path: path.read_text() for path in rewritten}
    for path, new in rewritten.items():
        if new != original[path]:
            path.write_text(new)
    write_generated(rm)
    for path in rewritten:
        # Report only edits to hand-written text. Regenerating the README's index
        # moves the index's own links anyway.
        before, after = original[path], path.read_text()
        if path == rm.readme:
            before, after = (splice(t, INDEX_BEGIN, INDEX_END, "", path) for t in (before, after))
        if before != after:
            print(f"Updated links in {path}.")
    print(f"Closed {args.id} as {args.outcome}: {target}.")
    return 0


def cmd_init(rm: Roadmap, args: argparse.Namespace) -> int:
    template = Path(__file__).resolve().parent.parent / "assets" / "template"
    if not template.is_dir():
        raise UsageError(f"init runs from the skill's own copy of roadmap.py; {template} is missing")
    script = Path(args.script)
    sources = [p for p in sorted(template.rglob("*")) if p.is_file()]
    targets = {src: rm.dir / src.relative_to(template) for src in sources}
    if clashes := [str(t) for t in targets.values() if t.exists()]:
        raise UsageError(f"refusing to overwrite {', '.join(clashes)}")

    for src, dest in targets.items():
        dest.parent.mkdir(parents=True, exist_ok=True)
        if src.suffix in (".md", ".toml"):
            dest.write_text(src.read_text().replace("{{script}}", script.as_posix()))
        else:
            shutil.copyfile(src, dest)
    if not (script.exists() and script.resolve() == Path(__file__).resolve()):
        script.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(Path(__file__), script)
    write_generated(open_roadmap(rm.dir))
    print(f"Created {rm.dir}/ and {script} (roadmap.py {__version__}).")
    return 0


def _date(text: str) -> datetime.date:
    try:
        return datetime.date.fromisoformat(text)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"{text!r} is not a YYYY-MM-DD date") from exc


def build_parser() -> argparse.ArgumentParser:
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--dir", default="roadmap", help="the roadmap directory (default: roadmap)")
    dated = argparse.ArgumentParser(add_help=False)
    dated.add_argument("--date", type=_date, help="use this date instead of today (YYYY-MM-DD)")

    parser = argparse.ArgumentParser(prog="roadmap.py", description=__doc__.split("\n\n")[0])
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    sub = parser.add_subparsers(dest="command", required=True, metavar="command")

    p = sub.add_parser("init", parents=[common], help="create roadmap/ and vendor this script")
    p.add_argument("--script", default="tools/roadmap.py", help="where to copy this script (default: tools/roadmap.py)")
    p.set_defaults(run=cmd_init)

    p = sub.add_parser("check", parents=[common], help="validate everything; exit 1 on any problem (for CI)")
    p.add_argument("--base", help="git ref to hold archive/ append-only against, e.g. origin/main")
    p.set_defaults(run=cmd_check)

    p = sub.add_parser("index", parents=[common], help="validate, then regenerate README.md's index and done.md")
    p.set_defaults(run=cmd_index)

    p = sub.add_parser("new", parents=[common, dated], help="file a new item")
    p.add_argument("id", help="kebab-case slug; becomes items/<id>.md")
    p.add_argument("--title", required=True)
    p.add_argument("--bucket", required=True, choices=BUCKETS)
    p.add_argument("--blocked-on", help="the undecided question (required for 'later')")
    p.add_argument("--gate", help="the bar the work has to clear")
    p.add_argument("--ref", action="append", default=[], metavar="KIND:VALUE", help="repeatable, e.g. files:src/app.py")
    p.add_argument("--body", help="the prose; a placeholder that fails `check` otherwise")
    p.set_defaults(run=cmd_new)

    p = sub.add_parser("move", parents=[common], help="move an item to another bucket, at the bottom of it")
    p.add_argument("id")
    p.add_argument("--bucket", required=True, choices=BUCKETS)
    p.add_argument("--blocked-on", help="the undecided question (required when moving to 'later')")
    p.set_defaults(run=cmd_move)

    p = sub.add_parser("close", parents=[common, dated], help="archive an item that shipped or was declined")
    p.add_argument("id")
    p.add_argument("--outcome", required=True, choices=OUTCOMES)
    p.add_argument("--as", dest="shipped_as", help="what it shipped as: a change, PR or release name")
    p.set_defaults(run=cmd_close)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.run(open_roadmap(args.dir), args)
    except UsageError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
